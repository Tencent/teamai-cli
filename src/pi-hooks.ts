/**
 * Pi Coding Agent hook injection.
 *
 * Pi discovers TypeScript extensions from ~/.pi/agent/extensions and from a
 * project .pi/extensions directory, auto-loading both. Only ONE copy is ever
 * written, in the user agent dir — a project copy would double-dispatch every
 * lifecycle event (the same single-copy policy as the OMP adapter). A
 * TeamAI-marked project copy left by an earlier revision is removed during
 * the next sync of that project. Pi has no settings file for self mode to
 * commit, so a fresh clone still needs one `teamai init`/`pull` on that
 * machine before Pi hooks are active there. The extension always dispatches
 * — hook-dispatch has no per-project exclusion check for any tool, so a
 * single shared file has no way to skip a project that has excluded Pi; the
 * `cwd` on STDIN only lets downstream handlers resolve the right project
 * context, not opt a project out. A targeted removal (scoped `uninstall` or
 * `hooks remove`) therefore deletes this one global copy outright, same as
 * the OMP adapter. The extension bridges TeamAI's built-in lifecycle events,
 * and runs the team's hooks/hooks.yaml entries through bridged-team-hooks.ts:
 * a PreToolUse hook can block a tool call on `tool_call`. Pi profile overrides (`PI_CODING_AGENT_DIR` /
 * `PI_CONFIG_DIR`), which relocate the agent directory, are not supported —
 * same as the OMP adapter — and the default `~/.pi/agent/` layout is used.
 */

import path from 'node:path';
import { generatedFileState, writeIfChanged, remove } from './utils/fs.js';
import { earlierHookAdapterDir, hookAdapterDir } from './locate.js';
import { log } from './utils/logger.js';
import { resolveCliEntry } from './builtin-hooks.js';
import { bridgedTeamHookFile } from './bridged-team-hooks.js';

/** Filename of the TeamAI-managed Pi extension. */
export const PI_HOOK_FILE = 'teamai-hooks.ts';

const TEAMAI_MARKER = '[teamai]';

/** Project-local Pi extension directory used only to clean up legacy copies. */
export function resolvePiProjectExtensionsDir(baseDir: string): string {
  return path.join(baseDir, '.pi', 'extensions');
}

/** Build the generated Pi extension source. */
export function buildPiExtensionSource(entry = resolveCliEntry()): string {
  if (!entry) throw new Error('Cannot resolve the teamai CLI entry; run `teamai hooks inject` from the installed CLI.');
  return `// ${TEAMAI_MARKER} hooks extension — generated by teamai, do not edit by hand.
//
// Bridges Pi extension events to the shared teamai hook-dispatch entry
// point. The child process receives the same JSON payload as shell-based hooks
// (cwd / session_id / tool_name / tool_input / prompt, and on post-tool-use the
// tool's text output and status). Errors and timeouts are swallowed so a
// missing teamai binary never blocks the Pi session. The team's hooks run only
// on the events the team has one on: a PreToolUse hook can block a tool call.

import { spawn } from "node:child_process";
import fs from "node:fs";

const NODE = ${JSON.stringify(process.execPath)};
const ENTRY = ${JSON.stringify(entry)};
const TEAM_HOOKS_FILE = ${JSON.stringify(bridgedTeamHookFile('pi'))};
/** Pi waits for a handler with no limit; the team hooks keep their own timeouts, this bounds the dispatch. */
const TEAM_HOOKS_TIMEOUT_MS = 600000;

/** The host session id (Pi's bash tool exports it as PI_SESSION_ID), read defensively. */
const sessionOf = (ctx) => {
  try {
    const id = ctx && ctx.sessionManager && ctx.sessionManager.getSessionId();
    return typeof id === "string" && id ? { session_id: id } : {};
  } catch {
    return {};
  }
};

/** A tool result's text parts, joined; undefined when it has no content list. */
const textOf = (content) => Array.isArray(content)
  ? content.filter((part) => part && part.type === "text" && typeof part.text === "string").map((part) => part.text).join("\\n")
  : undefined;

/** @param {any} pi Pi ExtensionAPI */
export default function teamaiHooks(pi) {
  const toolInputs = new Map();
  const dispatch = async (event, ctx, payload) => {
    try {
      const cwd = ctx.cwd;
      const args = ["hook-dispatch", event, "--tool", "pi"];
      const child = spawn(NODE, [ENTRY, ...args], {
        cwd,
        stdio: ["pipe", "ignore", "ignore"],
        windowsHide: true,
        shell: false,
      });
      const stdin = JSON.stringify({ cwd, ...sessionOf(ctx), ...(payload || {}) });
      child.stdin?.on("error", () => {});
      child.stdin?.end(stdin);
      await new Promise((resolve) => {
        let settled = false;
        const finish = () => {
          if (settled) return;
          settled = true;
          clearTimeout(timer);
          resolve(undefined);
        };
        const timer = setTimeout(() => {
          try { child.kill(); } catch {}
          finish();
        }, 15000);
        child.once("close", finish);
        child.once("error", finish);
      });
    } catch {
      // never block the agent
    }
  };

  // The member's culture, claudemd and recall blocks for a project session,
  // or "" (user scope, or teamai unavailable). Fetched once per session.
  let instructions;
  const loadInstructions = (ctx) => new Promise((resolve) => {
    try {
      const cwd = ctx.cwd;
      const child = spawn(NODE, [ENTRY, "hook-dispatch", "instructions", "--tool", "pi"], {
        cwd,
        stdio: ["pipe", "pipe", "ignore"],
        windowsHide: true,
        shell: false,
      });
      let out = "";
      const finish = () => {
        clearTimeout(timer);
        try {
          const text = out.trim() ? JSON.parse(out).hookSpecificOutput?.additionalContext : undefined;
          resolve(typeof text === "string" ? text : "");
        } catch {
          resolve("");
        }
      };
      const timer = setTimeout(() => {
        try { child.kill(); } catch {}
        out = "";
        finish();
      }, 15000);
      child.stdout?.on("data", (chunk) => { out += chunk; });
      child.stdin?.on("error", () => {});
      child.stdin?.end(JSON.stringify({ cwd, ...sessionOf(ctx) }));
      child.once("close", finish);
      child.once("error", () => { out = ""; finish(); });
    } catch {
      resolve("");
    }
  });

  // The team's hooks for a Claude event (hooks/hooks.yaml), run by
  // \`teamai hook-dispatch <Event> --tool pi --team-hooks\` when the team has
  // one on it: {block} for a PreToolUse hook that refuses, {context} for what
  // a SessionStart or UserPromptSubmit hook adds, else undefined. What a hook
  // that failed or timed out wrote on stderr goes to Pi's console. Never
  // rejects: Pi blocks a tool call whose handler throws.
  const teamHooks = (event, ctx, payload) => new Promise((resolve) => {
    try {
      const hooks = JSON.parse(fs.readFileSync(TEAM_HOOKS_FILE, "utf8")).hooks;
      if (!hooks || !Array.isArray(hooks[event]) || hooks[event].length === 0) return resolve(undefined);
      const cwd = ctx.cwd;
      const child = spawn(NODE, [ENTRY, "hook-dispatch", event, "--tool", "pi", "--team-hooks"], {
        cwd,
        stdio: ["pipe", "pipe", "pipe"],
        windowsHide: true,
        shell: false,
      });
      let out = "";
      let err = "";
      const finish = () => {
        clearTimeout(timer);
        if (err.trim()) console.error(err.trimEnd());
        err = "";
        try {
          resolve(out.trim() ? JSON.parse(out) : undefined);
        } catch {
          resolve(undefined);
        }
      };
      const timer = setTimeout(() => {
        try { child.kill(); } catch {}
        out = "";
        finish();
      }, TEAM_HOOKS_TIMEOUT_MS);
      child.stdout?.on("data", (chunk) => { out += chunk; });
      child.stderr?.on("data", (chunk) => { err += chunk; });
      child.stdin?.on("error", () => {});
      child.stdin?.end(JSON.stringify({ cwd, ...sessionOf(ctx), ...(payload || {}) }));
      child.once("close", finish);
      child.once("error", () => { out = ""; finish(); });
    } catch {
      resolve(undefined);
    }
  });

  // What the team's SessionStart hooks added at the session's start, for its first run.
  let started;

  pi.on("session_start", async (_event, ctx) => {
    await dispatch("session-start", ctx);
    instructions = loadInstructions(ctx);
    started = teamHooks("SessionStart", ctx);
  });

  pi.on("agent_settled", async (_event, ctx) => {
    await dispatch("stop", ctx);
    await teamHooks("Stop", ctx);
  });

  // Pi renders the system prompt again for every run, so adding the blocks
  // to this run's prompt reaches the model once, without piling up. For the
  // same reason the SessionStart hooks run again each run after the first:
  // what they print follows what a prompt hook changed (#1492).
  pi.on("before_agent_start", async (event, ctx) => {
    const session = started ?? teamHooks("SessionStart", ctx);
    started = undefined;
    await dispatch("prompt-submit", ctx, { prompt: event.prompt });
    const text = await (instructions ??= loadInstructions(ctx));
    // A run an extension starts (messageType "custom") carries no user prompt.
    const prompt = typeof event.prompt === "string" ? await teamHooks("UserPromptSubmit", ctx, { prompt: event.prompt }) : undefined;
    const added = [text, (await session)?.context, prompt?.context].filter((part) => typeof part === "string" && part);
    return added.length ? { systemPrompt: [event.systemPrompt, ...added].join("\\n\\n") } : undefined;
  });

  // Fires before the tool runs, unlike tool_execution_start, and a {block} result stops it.
  pi.on("tool_call", async (event, ctx) => {
    const decision = await teamHooks("PreToolUse", ctx, { tool_name: event.toolName, tool_input: event.input });
    return decision && typeof decision.block === "string" ? { block: true, reason: decision.block } : undefined;
  });

  pi.on("tool_execution_start", async (event) => {
    toolInputs.set(event.toolCallId, event.args);
  });

  // The result is what the model saw; isError is set for a failed call,
  // including a bash command that exits non-zero.
  pi.on("tool_execution_end", async (event, ctx) => {
    const payload = {
      tool_name: event.toolName,
      tool_input: toolInputs.get(event.toolCallId) || {},
      tool_response: textOf(event.result && event.result.content),
      tool_status: event.isError === true ? "failure" : event.isError === false ? "success" : "unknown",
    };
    toolInputs.delete(event.toolCallId);
    await dispatch("post-tool-use", ctx, payload);
    await teamHooks("PostToolUse", ctx, payload);
  });
}
`;
}

/**
 * Inject or refresh the single global TeamAI Pi extension. Mirrors the
 * ownership check `removePiHooks` already applies: a same-named file without
 * TeamAI's marker is left untouched rather than overwritten.
 */
export async function injectPiHooks(): Promise<void> {
  const dir = hookAdapterDir('pi-extension');
  const file = path.join(dir, PI_HOOK_FILE);
  if (await generatedFileState(file, `${TEAMAI_MARKER} hooks extension`) === 'foreign') {
    log.warn(`Skipping Pi hook injection: ${file} exists without the TeamAI marker`);
    return;
  }
  if (await writeIfChanged(file, buildPiExtensionSource())) {
    log.success(`Injected teamai Pi hook into ${file}`);
  } else {
    log.debug(`teamai Pi hook already up-to-date in ${file}`);
  }
}

/** Remove the generated extension from `extensionsDir`, by default the one Pi loads, if it has TeamAI's marker. */
export async function removePiHooks(extensionsDir = hookAdapterDir('pi-extension')): Promise<void> {
  const file = path.join(extensionsDir, PI_HOOK_FILE);
  if (!await hasPiHooks(extensionsDir)) return;
  await remove(file);
  log.success(`Removed teamai Pi hook from ${file}`);
}

/** Remove a TeamAI-managed project copy written by an earlier revision. */
export async function removePiProjectHooks(baseDir: string): Promise<void> {
  const file = path.join(resolvePiProjectExtensionsDir(baseDir), PI_HOOK_FILE);
  if (!await hasPiHooks(resolvePiProjectExtensionsDir(baseDir))) return;
  await remove(file);
  log.success(`Removed legacy project Pi hook from ${file}`);
}

function assertSafeSlug(slug: string): void {
  if (!slug || slug.includes('/') || slug.includes('\\') || slug.includes('..') || path.isAbsolute(slug)) {
    throw new Error(`Invalid Pi agent-hook slug: ${slug}`);
  }
}

/** Filename of one HTTP-source agent-hook extension, keyed by slug. */
function piAgentHookFile(slug: string, dir = hookAdapterDir('pi-extension')): string {
  return path.join(dir, `teamai-agent-${slug}.ts`);
}

/**
 * Check whether a specific `teamai-agent-<slug>.ts` file carries TeamAI's
 * per-slug marker. Mirrors `hasPiHooks` for the main extension — write/remove
 * on this file must never touch a same-named file a user authored by hand.
 */
export async function hasPiAgentHook(slug: string, dir?: string): Promise<boolean> {
  return await piAgentHookState(slug, dir) === 'teamai';
}

const piAgentHookState = (slug: string, dir?: string) => generatedFileState(piAgentHookFile(slug, dir), `${TEAMAI_MARKER} agent hook [${slug}]`);

/** Remove the agent-hook extension an earlier release installed for Pi; agent hooks now run from teamai's extension. */
export async function removePiAgentHook(slug: string): Promise<void> {
  assertSafeSlug(slug);
  // And the copy an earlier release left under the default home, which Pi reads once its home stops moving (#1221).
  for (const dir of [hookAdapterDir('pi-extension'), await earlierHookAdapterDir('pi-extension')]) {
    if (dir === null || !await hasPiAgentHook(slug, dir)) continue;
    await remove(piAgentHookFile(slug, dir));
    log.success(`Removed Pi agent hook [${slug}]`);
  }
}

/** Check whether the extension in `extensionsDir`, by default the one Pi loads, has TeamAI's marker. */
export async function hasPiHooks(extensionsDir = hookAdapterDir('pi-extension')): Promise<boolean> {
  const file = path.join(extensionsDir, PI_HOOK_FILE);
  return await generatedFileState(file, `${TEAMAI_MARKER} hooks extension`) === 'teamai';
}
