/**
 * Hermes agent hook injection.
 *
 * Writes a bash status-report script under `<hermesHome>/hooks/` and
 * registers it in config.yaml `hooks:` plus the shell-hooks allowlist.
 * Provides symmetric inject / remove helpers and a generic per-agent-hook
 * apply / remove pair for use by the local-agent pipeline (wired in a later
 * batch).
 */

import path from 'node:path';
import { chmod } from 'node:fs/promises';
import { generatedFileState, writeIfChanged, pathExists, remove } from './utils/fs.js';
import { log } from './utils/logger.js';
import { resolveCliEntry } from './builtin-hooks.js';
import { hookAdapterDirIn } from './locate.js';
import { toolHome } from './tool-home.js';
import { bridgedTeamHookEvents } from './bridged-team-hooks.js';
import { shellQuoteValue } from './utils/shell-profile.js';
import {
  upsertHermesHook,
  removeHermesHookByCommand,
  hasHermesHookCommands,
  addHermesAllowlist,
  removeHermesAllowlist,
  enableHermesPlugin,
  disableHermesPlugin,
} from './hermes-config.js';

/** Hermes hook event used for session-start status reporting. */
const REPORT_EVENT = 'on_session_start';

/** Name of teamai's Hermes plugin, also its `plugins.enabled` entry. */
export const HERMES_INSTRUCTIONS_PLUGIN = 'teamai-instructions';

/**
 * Characters Hermes allows one plugin prompt section. A larger section is
 * skipped, so teamai reports it rather than truncating the instructions.
 */
export const HERMES_SECTION_LIMIT = 4000;

/** Directory of teamai's Hermes plugin in `home`. */
export function getInstructionsPluginDir(home = toolHome('hermes')): string {
  return path.join(home, 'plugins', HERMES_INSTRUCTIONS_PLUGIN);
}

const PLUGIN_MARKER = '# [teamai] generated by teamai';

/**
 * Whether teamai may write or delete the plugin directory: it does not exist
 * yet, or its manifest carries teamai's marker. A same-named plugin of the
 * member's is never overwritten or removed.
 */
export async function ownsInstructionsPlugin(home = toolHome('hermes')): Promise<boolean> {
  const dir = getInstructionsPluginDir(home);
  if (!await pathExists(dir)) return true;
  return await generatedFileState(path.join(dir, 'plugin.yaml'), PLUGIN_MARKER) === 'teamai';
}

/** Why teamai left the plugin directory alone, and what to do. */
export function foreignInstructionsPlugin(): string {
  return `${getInstructionsPluginDir()} holds a plugin teamai did not write, so teamai left it unchanged and Hermes sessions in a project `
    + 'get no team instructions. Rename or move that plugin, then run `teamai hooks inject`.';
}

/**
 * The plugin adds the member's team instructions for the session's project
 * as a cache-safe system prompt section (#945). Hermes builds the section
 * once for a new session and keeps it through compression and resume.
 * Outside a project `hook-dispatch instructions` prints nothing and the
 * section is empty: the user-scope blocks are in SOUL.md.
 */
export function buildInstructionsPlugin(entry = resolveCliEntry()): { manifest: string; init: string } {
  if (!entry) throw new Error('Cannot resolve the teamai CLI entry; run `teamai hooks inject` from the installed CLI.');
  const manifest = [
    `${PLUGIN_MARKER}, do not edit.`,
    `name: ${HERMES_INSTRUCTIONS_PLUGIN}`,
    'version: "1"',
    'description: Adds the team instructions teamai resolves for this member and project.',
    '',
  ].join('\n');
  const init = [
    '"""[teamai] team instructions plugin, generated by teamai, do not edit."""',
    'import json',
    'import os',
    'import subprocess',
    '',
    '',
    'def _instructions(session_info):',
    '    cwd = session_info.get("cwd") or os.getcwd()',
    '    try:',
    '        result = subprocess.run(',
    `            [${JSON.stringify(process.execPath)}, ${JSON.stringify(entry)}, "hook-dispatch", "instructions", "--tool", "hermes"],`,
    '            input=json.dumps({"cwd": cwd, "session_id": session_info.get("session_id")}),',
    '            capture_output=True,',
    '            text=True,',
    '            cwd=cwd,',
    '            timeout=15,',
    '        )',
    '        out = result.stdout.strip()',
    '        text = json.loads(out)["hookSpecificOutput"]["additionalContext"] if out else ""',
    '    except Exception:',
    '        return ""',
    '    return text if isinstance(text, str) else ""',
    '',
    '',
    'def register(ctx):',
    '    ctx.register_system_prompt_section(',
    '        "teamai.instructions",',
    '        _instructions,',
    '        position="after_memory",',
    `        max_chars=${HERMES_SECTION_LIMIT},`,
    '    )',
    '',
  ].join('\n');
  return { manifest, init };
}

/** Absolute path to the generated status-report shell script in `home`. */
export function getReportScriptPath(home = toolHome('hermes')): string {
  return path.join(hookAdapterDirIn('hermes-plugin', home), 'teamai-status-report.sh');
}

/** Hermes tokenizes commands before execution; a script path is one argument. */
function reportCommand(scriptPath: string): string {
  return process.platform === 'win32' ? `"${scriptPath}"` : shellQuoteValue(scriptPath);
}

/**
 * Return the content of the status-report shell script.
 * The script shells out to `teamai hook-dispatch` and swallows all errors so
 * it never blocks the agent session.
 */
function buildReportScript(entry: string): string {
  return [
    '#!/usr/bin/env bash',
    '# [teamai] status-report hook — generated by teamai, do not edit.',
    `${shellQuoteValue(process.execPath)} ${shellQuoteValue(entry)} hook-dispatch session-start --tool hermes >/dev/null 2>&1 || true`,
    '',
  ].join('\n');
}

/** The script each team-hook entry runs, given the Claude event: one stable command per event, so its approval outlives an upgrade. */
export function getTeamHookScriptPath(home = toolHome('hermes')): string {
  return path.join(hookAdapterDirIn('hermes-plugin', home), 'teamai-team-hooks.sh');
}

function buildTeamHookScript(entry: string): string {
  return [
    '#!/usr/bin/env bash',
    '# [teamai] team hooks — generated by teamai, do not edit.',
    `exec ${shellQuoteValue(process.execPath)} ${shellQuoteValue(entry)} hook-dispatch "$1" --tool hermes --team-hooks`,
    '',
  ].join('\n');
}

/**
 * The Hermes event each team-hook entry hangs on, the Claude event it
 * dispatches, and the Claude events whose hooks it runs. SessionStart rides on
 * the first turn's pre_llm_call (the bridge runs it there): Hermes ignores
 * what an on_session_start hook prints. on_session_end ends every turn, as
 * Claude's Stop does.
 */
const TEAM_HOOK_ENTRIES: readonly { hermes: string; dispatch: string; runs: readonly string[] }[] = [
  { hermes: 'pre_tool_call', dispatch: 'PreToolUse', runs: ['PreToolUse'] },
  { hermes: 'post_tool_call', dispatch: 'PostToolUse', runs: ['PostToolUse'] },
  { hermes: 'pre_llm_call', dispatch: 'UserPromptSubmit', runs: ['UserPromptSubmit', 'SessionStart'] },
  { hermes: 'on_session_end', dispatch: 'Stop', runs: ['Stop'] },
];

/** Hermes clamps an entry's timeout to this many seconds. */
const HERMES_MAX_TIMEOUT = 300;

/**
 * Give each Hermes event the team has hooks on (in the bridged file) one
 * approved entry that runs them through teamai's bridge, and drop the
 * others. Returns whether anything changed.
 */
async function reconcileHermesTeamHooks(entry: string): Promise<boolean> {
  const events = await bridgedTeamHookEvents('hermes');
  const script = getTeamHookScriptPath();
  if (events.size === 0) return removeHermesTeamHooks();
  let changed = await writeIfChanged(script, buildTeamHookScript(entry));
  await chmod(script, 0o755).catch((e: Error) => log.warn(`Failed to chmod Hermes team hook script: ${e.message}`));
  for (const { hermes, dispatch, runs } of TEAM_HOOK_ENTRIES) {
    const command = `${reportCommand(script)} ${dispatch}`;
    const timeouts = runs.flatMap((event) => events.has(event) ? [events.get(event) ?? 60] : []);
    if (timeouts.length === 0) {
      changed = await removeHermesTeamHookEntry(hermes, command) || changed;
      continue;
    }
    // A first turn's pre_llm_call runs SessionStart's hooks, then UserPromptSubmit's.
    const timeout = Math.min(HERMES_MAX_TIMEOUT, timeouts.reduce((sum, seconds) => sum + seconds, 0));
    changed = await upsertHermesHook(hermes, { command, timeout }) || changed;
    changed = await addHermesAllowlist(hermes, command) || changed;
  }
  return changed;
}

/** Reconcile only the team-hook entries, leaving teamai's own Hermes hook as it is. */
export async function refreshHermesTeamHooks(): Promise<void> {
  const entry = resolveCliEntry();
  if (!entry) {
    log.warn('Hermes: cannot resolve the teamai CLI entry; run `teamai hooks inject` from the installed CLI.');
    return;
  }
  await reconcileHermesTeamHooks(entry);
}

async function removeHermesTeamHookEntry(event: string, command: string, home = toolHome('hermes')): Promise<boolean> {
  const registered = await hasHermesHookCommands([command], home);
  if (registered) await removeHermesHookByCommand(command, home);
  await removeHermesAllowlist(event, command, home);
  return registered;
}

/** Remove the team-hook entries, their approvals and their script from `home`. Returns whether any was there. */
async function removeHermesTeamHooks(home = toolHome('hermes')): Promise<boolean> {
  const script = getTeamHookScriptPath(home);
  let removed = false;
  for (const { hermes, dispatch } of TEAM_HOOK_ENTRIES) {
    removed = await removeHermesTeamHookEntry(hermes, `${reportCommand(script)} ${dispatch}`, home) || removed;
  }
  if (await pathExists(script)) {
    await remove(script);
    removed = true;
  }
  return removed;
}

/**
 * Inject (or refresh) the teamai Hermes status-report hook.
 *
 * Steps:
 * 1. Create the `hooks/` directory under the Hermes home.
 * 2. Write the shell script and mark it executable (0o755).
 * 3. Register the script in config.yaml `hooks.on_session_start`.
 * 4. Add the script path to the shell-hooks allowlist.
 */
export async function injectHermesHooks(): Promise<void> {
  const entry = resolveCliEntry();
  if (!entry) {
    log.warn('Hermes: cannot resolve the teamai CLI entry; run `teamai hooks inject` from the installed CLI.');
    return;
  }
  const scriptPath = getReportScriptPath();
  const command = reportCommand(scriptPath);
  const scriptChanged = await writeIfChanged(scriptPath, buildReportScript(entry));
  try {
    await chmod(scriptPath, 0o755);
  } catch (e) {
    log.warn(`Failed to chmod Hermes hook script: ${(e as Error).message}`);
  }
  // Retire the unquoted command as well as its exact-match approval on upgrade.
  await removeHermesHookByCommand(scriptPath);
  await removeHermesAllowlist(REPORT_EVENT, scriptPath);
  const hookChanged = await upsertHermesHook(REPORT_EVENT, { command, timeout: 60 });
  const allowlistChanged = await addHermesAllowlist(REPORT_EVENT, command);
  let pluginChanged = false;
  if (await ownsInstructionsPlugin()) {
    const plugin = buildInstructionsPlugin(entry);
    const pluginDir = getInstructionsPluginDir();
    const manifestChanged = await writeIfChanged(path.join(pluginDir, 'plugin.yaml'), plugin.manifest);
    const initChanged = await writeIfChanged(path.join(pluginDir, '__init__.py'), plugin.init);
    const pluginEnabled = await enableHermesPlugin(HERMES_INSTRUCTIONS_PLUGIN);
    pluginChanged = manifestChanged || initChanged || pluginEnabled;
  } else {
    log.warn(`Skipping the Hermes instructions plugin: ${getInstructionsPluginDir()} exists without the TeamAI marker`);
  }
  const teamHooksChanged = await reconcileHermesTeamHooks(entry);
  if (scriptChanged || hookChanged || allowlistChanged || pluginChanged || teamHooksChanged) {
    log.success('Injected teamai Hermes hook into ' + scriptPath);
  } else {
    log.debug(`teamai Hermes hook already up-to-date in ${scriptPath}`);
  }
}

/** Managed Hermes artifacts in `home` still requiring cleanup, including dangling registrations. */
export async function hasHermesHooks(home = toolHome('hermes')): Promise<boolean> {
  const script = getReportScriptPath(home);
  return await pathExists(script) || await pathExists(getTeamHookScriptPath(home))
    || (await pathExists(getInstructionsPluginDir(home)) && await ownsInstructionsPlugin(home))
    || await hasHermesHookCommands([script, reportCommand(script)], home);
}

/**
 * Remove the teamai Hermes status-report hook.
 *
 * Steps:
 * 1. Remove the script from config.yaml `hooks:`.
 * 2. Remove the script from the shell-hooks allowlist.
 * 3. Delete the script file if it exists.
 */
export async function removeHermesHooks(home = toolHome('hermes')): Promise<void> {
  const existed = await hasHermesHooks(home);
  const scriptPath = getReportScriptPath(home);
  for (const command of [scriptPath, reportCommand(scriptPath)]) {
    await removeHermesHookByCommand(command, home);
    await removeHermesAllowlist(REPORT_EVENT, command, home);
  }
  if (await pathExists(scriptPath)) {
    await remove(scriptPath);
  }
  if (await ownsInstructionsPlugin(home)) {
    await disableHermesPlugin(HERMES_INSTRUCTIONS_PLUGIN, home);
    await remove(getInstructionsPluginDir(home));
  }
  await removeHermesTeamHooks(home);
  if (existed) log.success('Removed teamai Hermes hook from ' + scriptPath);
}

/** The Hermes shell-hook event an earlier release registered each agent hook event under (#1220). */
const AGENT_TO_HERMES_EVENTS: Readonly<Record<string, string>> = {
  SessionStart: 'on_session_start',
  UserPromptSubmit: 'pre_llm_call',
  PreToolUse: 'pre_tool_call',
  PostToolUse: 'post_tool_call',
  Stop: 'on_session_end',
};

/**
 * Remove the agent hook entry an earlier release registered in Hermes
 * config.yaml and its allowlist; agent hooks now run through the team-hook
 * entries.
 *
 * @param opts - At minimum `command` is required; providing `event` also
 *   removes the allowlist entry for that specific `(event, command)` pair.
 */
export async function removeHermesAgentHook(opts: {
  slug: string;
  event?: string;
  command: string;
}): Promise<void> {
  await removeHermesHookByCommand(opts.command);
  if (opts.event !== undefined) {
    // Versions before #1220 allowlisted the agent event name itself.
    for (const event of new Set([AGENT_TO_HERMES_EVENTS[opts.event], opts.event])) {
      if (event) await removeHermesAllowlist(event, opts.command);
    }
  }
  log.success(`Removed Hermes agent hook [${opts.slug}]`);
}
