import { afterEach, beforeEach, describe, it, expect, vi } from 'vitest';
import { parseMrUrl, formatComment, postOrUpdateMrComment, postIndividualComments, postCodebaseGraphComment } from '../ci/mr-comment.js';
import type { LearningDraft, CodebaseSuggestion } from '../types.js';

describe('parseMrUrl', () => {
  it('parses a GitHub PR URL', () => {
    const result = parseMrUrl('https://github.com/owner/repo/pull/42');
    expect(result).toEqual({ provider: 'github', owner: 'owner', repo: 'repo', number: '42' });
  });

  it('parses a TGit MR URL (single-level group)', () => {
    const result = parseMrUrl('https://git.woa.com/team/project/merge_requests/7');
    expect(result).toEqual({ provider: 'tgit', owner: 'team', repo: 'project', number: '7' });
  });

  it('parses a TGit MR URL (multi-level group)', () => {
    const result = parseMrUrl('https://git.woa.com/group/sub/project/merge_requests/123');
    expect(result).toEqual({ provider: 'tgit', owner: 'group/sub', repo: 'project', number: '123' });
  });

  it('parses a GitLab MR URL (self-hosted instance)', () => {
    const result = parseMrUrl('https://gitlab.example.com/group/project/-/merge_requests/88');
    expect(result).toEqual({ provider: 'gitlab', owner: 'group', repo: 'project', number: '88' });
  });

  it('parses a GitLab MR URL (nested subgroup)', () => {
    const result = parseMrUrl('https://gitlab.com/group/sub/proj/-/merge_requests/5');
    expect(result).toEqual({ provider: 'gitlab', owner: 'group/sub', repo: 'proj', number: '5' });
  });

  it('throws on an unsupported URL', () => {
    expect(() => parseMrUrl('https://example.com/org/repo/pull/1')).toThrow('only GitHub, TGit and GitLab are supported');
  });
});

describe('formatComment', () => {
  const marker = '<!-- teamai:ci-extract -->';

  it('formats a comment with a learning and suggestions', () => {
    const learning: LearningDraft = {
      title: '修复数据库连接泄漏',
      content: '---\ntitle: 修复数据库连接泄漏\n---\n\n## 背景\n连接未关闭',
    };
    const suggestions: CodebaseSuggestion[] = [
      { section: '架构', action: 'update', content: '新增连接池管理模块' },
    ];

    const result = formatComment(learning, suggestions, marker);

    expect(result).toContain(marker);
    expect(result).toContain('修复数据库连接泄漏');
    expect(result).toContain('### Learning');
    expect(result).toContain('### Codebase.md update suggestions');
    expect(result).toContain('| 架构 | update |');
    expect(result).toContain('Auto-generated by');
  });

  it('says there is nothing to extract without a learning or suggestions', () => {
    const result = formatComment(undefined, undefined, marker);
    expect(result).toContain(marker);
    expect(result).toContain('No knowledge to extract from this MR.');
    expect(result).not.toContain('### Learning');
  });

  it('formats a learning without suggestions', () => {
    const learning: LearningDraft = {
      title: '测试标题',
      content: '内容',
    };
    const result = formatComment(learning, [], marker);
    expect(result).toContain('### Learning');
    expect(result).not.toContain('### Codebase.md update suggestions');
  });
});

describe('postOrUpdateMrComment API failures', () => {
  beforeEach(() => {
    // Pin the instance host so the developer's local GITLAB_URL never leaks in.
    vi.stubEnv('GITLAB_URL', 'https://gitlab.com');
  });
  afterEach(() => {
    vi.unstubAllEnvs();
    vi.unstubAllGlobals();
  });

  it('fails without creating a duplicate GitHub comment when listing comments fails', async () => {
    vi.stubEnv('GITHUB_TOKEN', 'test-token');
    const fetchMock = vi.fn().mockResolvedValue(new Response(null, { status: 503 }));
    vi.stubGlobal('fetch', fetchMock);

    await expect(postOrUpdateMrComment(
      'https://github.com/acme/app/pull/7', undefined, undefined,
    )).rejects.toThrow('GitHub comment list request failed (503)');

    expect(fetchMock).toHaveBeenCalledTimes(1);
    expect(fetchMock.mock.calls[0][1]?.method).toBe('GET');
  });

  it('fails without creating a duplicate TGit note when listing notes fails', async () => {
    vi.stubEnv('TGIT_TOKEN', 'test-token');
    const fetchMock = vi.fn()
      .mockResolvedValueOnce(new Response(JSON.stringify([{ id: 42, iid: 7 }]), { status: 200 }))
      .mockResolvedValueOnce(new Response(null, { status: 503 }));
    vi.stubGlobal('fetch', fetchMock);

    await expect(postOrUpdateMrComment(
      'https://git.woa.com/acme/app/merge_requests/7', undefined, undefined,
    )).rejects.toThrow('TGit note list request failed (503)');

    expect(fetchMock).toHaveBeenCalledTimes(2);
    expect(fetchMock.mock.calls.some(([, init]) => init?.method === 'POST')).toBe(false);
  });

  it('fails without creating a duplicate GitLab note when listing notes fails', async () => {
    vi.stubEnv('GITLAB_TOKEN', 'test-token');
    const fetchMock = vi.fn().mockResolvedValue(new Response(null, { status: 503 }));
    vi.stubGlobal('fetch', fetchMock);

    await expect(postOrUpdateMrComment(
      'https://gitlab.com/acme/app/-/merge_requests/7', undefined, undefined,
    )).rejects.toThrow('GitLab note list request failed (503)');

    expect(fetchMock).toHaveBeenCalledTimes(1);
    expect(fetchMock.mock.calls[0][1]?.method).toBe('GET');
  });

  it('never follows redirects when calling the GitLab notes API (token must not leak)', async () => {
    vi.stubEnv('GITLAB_TOKEN', 'test-token');
    const fetchMock = vi.fn().mockResolvedValue(
      new Response(null, { status: 302, headers: { location: 'https://evil.example/x' } }),
    );
    vi.stubGlobal('fetch', fetchMock);

    await expect(postOrUpdateMrComment(
      'https://gitlab.com/acme/app/-/merge_requests/7', undefined, undefined,
    )).rejects.toThrow(/redirect/i);

    // Every request must opt out of redirect following.
    for (const [, init] of fetchMock.mock.calls) {
      expect(init?.redirect).toBe('manual');
    }
  });

  it('finds a marker note on a later page and updates it in place', async () => {
    vi.stubEnv('GITLAB_TOKEN', 'test-token');
    const marker = '<!-- teamai:ci-extract -->';
    const page1 = JSON.stringify(Array.from({ length: 100 }, (_, i) => ({ id: 200 + i, body: `chat ${i}` })));
    const page2 = JSON.stringify([{ id: 9, body: `${marker}\nlearning body` }]);
    const fetchMock = vi.fn(async (url: string, _init?: RequestInit) => {
      if (url.includes('&page=1')) {
        return new Response(page1, { status: 200, headers: { 'x-next-page': '2' } });
      }
      if (url.includes('&page=2')) return new Response(page2, { status: 200 });
      if (url.includes('/notes/9')) {
        return new Response(JSON.stringify({}), { status: 200 });
      }
      throw new Error(`unexpected ${url}`);
    });
    vi.stubGlobal('fetch', fetchMock);

    await postOrUpdateMrComment(
      'https://gitlab.com/acme/app/-/merge_requests/7',
      { learning: { title: 'T', content: 'C' } } as never,
      undefined,
    );

    const put = fetchMock.mock.calls.find(([, init]) => init?.method === 'PUT');
    expect(put?.[0]).toContain('/notes/9');
    expect(fetchMock.mock.calls.some(([, init]) => init?.method === 'POST')).toBe(false);
  });

  it('updates the most recently edited marker even when it is the oldest of more than 2,000 notes', async () => {
    vi.stubEnv('GITLAB_TOKEN', 'test-token');
    const marker = '<!-- teamai:ci-extract -->';
    const notes = Array.from({ length: 2_001 }, (_, i) => ({
      id: i + 100,
      body: `chat ${i}`,
      created_at: new Date(Date.UTC(2026, 0, 1) + i * 1_000).toISOString(),
      updated_at: new Date(Date.UTC(2026, 0, 1) + i * 1_000).toISOString(),
    }));
    notes.push(
      { id: 9, body: marker, created_at: '2025-01-01T00:00:00Z', updated_at: '2026-10-26T00:00:00Z' },
      { id: 8, body: marker, created_at: '2025-02-01T00:00:00Z', updated_at: '2026-10-25T00:00:00Z' },
    );
    const fetchMock = vi.fn(async (url: string, init?: RequestInit) => {
      if (url.includes('/notes?')) {
        const query = new URL(url).searchParams;
        const orderBy = query.get('order_by') === 'updated_at' ? 'updated_at' : 'created_at';
        const direction = query.get('sort') === 'asc' ? 1 : -1;
        const sorted = [...notes].sort((a, b) => direction * a[orderBy].localeCompare(b[orderBy]));
        const page = Number(query.get('page'));
        return new Response(JSON.stringify(sorted.slice((page - 1) * 100, page * 100)), {
          headers: page * 100 < notes.length ? { 'x-next-page': String(page + 1) } : {},
        });
      }
      if (url.endsWith('/notes/9') && init?.method === 'PUT') return new Response('{}');
      throw new Error(`unexpected ${url} ${init?.method}`);
    });
    vi.stubGlobal('fetch', fetchMock);

    await expect(postOrUpdateMrComment(
      'https://gitlab.com/acme/app/-/merge_requests/7', { title: 'T', content: 'C' }, undefined,
    )).resolves.toEqual({ created: false });
    expect(fetchMock).toHaveBeenCalledTimes(2);
    expect(fetchMock.mock.calls[1][0]).toContain('/notes/9');
  });

  describe.each([1, 20])('marker found on page %i with more pages remaining', (markerPage) => {
    it.each(['summary', 'custom', 'individual', 'graph'] as const)('updates the %s comment without fetching later pages', async (kind) => {
      vi.stubEnv('GITLAB_TOKEN', 'test-token');
      const marker = kind === 'custom' ? '<!-- custom-learning -->'
        : kind === 'individual' ? '<!-- teamai:ci-extract:learning -->'
          : kind === 'graph' ? '<!-- teamai:ci-extract:codebase-graph -->'
            : '<!-- teamai:ci-extract -->';
      const fetchMock = vi.fn(async (url: string, init?: RequestInit) => {
        if (url.includes('/notes?')) {
          const page = Number(new URL(url).searchParams.get('page'));
          const notes = Array.from({ length: 100 }, (_, i) => ({ id: page * 100 + i, body: `chat ${i}` }));
          // Quoting the marker must not stop the lookup on an earlier page.
          notes[0].body = `Please explain ${marker}`;
          if (page === markerPage) notes[1] = { id: 9, body: `old content\n${marker}` };
          return new Response(JSON.stringify(notes), { headers: { 'x-next-page': String(page + 1) } });
        }
        if (url.endsWith('/notes/9') && init?.method === 'PUT') return new Response('{}');
        throw new Error(`unexpected ${url} ${init?.method}`);
      });
      vi.stubGlobal('fetch', fetchMock);
      const url = 'https://gitlab.com/acme/app/-/merge_requests/7';
      const learning = { title: 'T', content: 'C' };

      if (kind === 'graph') await postCodebaseGraphComment(url, { added: ['a.ts'], removed: [] });
      else if (kind === 'individual') await postIndividualComments(url, learning, undefined);
      else await postOrUpdateMrComment(url, learning, undefined, marker);

      expect(fetchMock.mock.calls.filter(([, init]) => init?.method === 'GET')).toHaveLength(markerPage);
      expect(fetchMock.mock.calls.filter(([, init]) => init?.method === 'PUT')).toHaveLength(1);
      expect(fetchMock.mock.calls.some(([, init]) => init?.method === 'POST')).toBe(false);
    });
  });

  it('refuses to post a duplicate when the marker is still missing at the page limit', async () => {
    vi.stubEnv('GITLAB_TOKEN', 'test-token');
    const fetchMock = vi.fn(async (url: string, _init?: RequestInit) => {
      const page = Number(new URL(url).searchParams.get('page'));
      return new Response('[]', { headers: { 'x-next-page': String(page + 1) } });
    });
    vi.stubGlobal('fetch', fetchMock);

    await expect(postOrUpdateMrComment(
      'https://gitlab.com/acme/app/-/merge_requests/7', undefined, undefined,
    )).rejects.toThrow('GitLab note list has more than 20 pages');

    expect(fetchMock).toHaveBeenCalledTimes(20);
    expect(fetchMock.mock.calls.every(([, init]) => init?.method === 'GET')).toBe(true);
  });

  it('fails without posting when a later page cannot be read before finding the marker', async () => {
    vi.stubEnv('GITLAB_TOKEN', 'test-token');
    const fetchMock = vi.fn()
      .mockResolvedValueOnce(new Response('[]', { headers: { 'x-next-page': '2' } }))
      .mockResolvedValueOnce(new Response(null, { status: 503 }));
    vi.stubGlobal('fetch', fetchMock);

    await expect(postOrUpdateMrComment(
      'https://gitlab.com/acme/app/-/merge_requests/7', undefined, undefined,
    )).rejects.toThrow('GitLab note list request failed (503)');
    expect(fetchMock).toHaveBeenCalledTimes(2);
    expect(fetchMock.mock.calls.every(([, init]) => init?.method === 'GET')).toBe(true);
  });

  it('ignores a human note that only quotes the marker', async () => {
    vi.stubEnv('GITLAB_TOKEN', 'test-token');
    const marker = '<!-- teamai:ci-extract -->';
    const notes = JSON.stringify([
      { id: 5, body: `I think ${marker} is wrong` },
    ]);
    const fetchMock = vi.fn(async (url: string, _init?: RequestInit) => {
      if (url.includes('/notes?')) return new Response(notes, { status: 200 });
      if (url.includes('/notes/')) return new Response(JSON.stringify({}), { status: 200 });
      if (url.endsWith('/notes')) return new Response(JSON.stringify({ id: 42 }), { status: 201 });
      throw new Error(`unexpected ${url}`);
    });
    vi.stubGlobal('fetch', fetchMock);

    await postOrUpdateMrComment(
      'https://gitlab.com/acme/app/-/merge_requests/7',
      { learning: { title: 'T', content: 'C' } } as never,
      undefined,
    );

    // The quoted mention must not be treated as our own comment: post a new one.
    expect(fetchMock.mock.calls.some(([, init]) => init?.method === 'POST')).toBe(true);
    expect(fetchMock.mock.calls.some(([, init]) => init?.method === 'PUT')).toBe(false);
  });

  it('refuses a GitLab MR URL whose host is not the configured instance', async () => {
    vi.stubEnv('GITLAB_TOKEN', 'test-token');
    const fetchMock = vi.fn();
    vi.stubGlobal('fetch', fetchMock);

    await expect(postOrUpdateMrComment(
      'https://evil.example/acme/app/-/merge_requests/7', undefined, undefined,
    )).rejects.toThrow('Refusing to fetch GitLab MR');

    expect(fetchMock).not.toHaveBeenCalled();
  });

  it('posts a new GitLab codebase-graph comment when none exists', async () => {
    vi.stubEnv('GITLAB_TOKEN', 'test-token');
    const fetchMock = vi.fn(async (url: string, init?: RequestInit) => {
      if (url.includes('/notes?')) return new Response('[]', { status: 200 });
      if (url.endsWith('/notes') && init?.method === 'POST') {
        return new Response(JSON.stringify({ id: 42 }), { status: 201 });
      }
      throw new Error(`unexpected ${url} ${init?.method}`);
    });
    vi.stubGlobal('fetch', fetchMock);

    await postCodebaseGraphComment(
      'https://gitlab.com/acme/app/-/merge_requests/7',
      { added: ['a.ts'], removed: [] },
    );

    const post = fetchMock.mock.calls.find(([, init]) => init?.method === 'POST');
    expect(post).toBeDefined();
    expect(String(post?.[1]?.body)).toContain('teamai:ci-extract:codebase-graph');
  });

  it('updates an existing GitLab codebase-graph comment whose marker is on the LAST line', async () => {
    vi.stubEnv('GITLAB_TOKEN', 'test-token');
    const marker = '<!-- teamai:ci-extract:codebase-graph -->';
    // The graph formatter puts the marker at the END of the body, not the start.
    const existing = JSON.stringify([
      { id: 9, body: `## 📊 Codebase 知识图谱变更\n\nold\n---\n> 👎 ...\n${marker}` },
    ]);
    const fetchMock = vi.fn(async (url: string, init?: RequestInit) => {
      if (url.includes('/notes?')) return new Response(existing, { status: 200 });
      if (url.includes('/notes/9') && init?.method === 'PUT') {
        return new Response(JSON.stringify({}), { status: 200 });
      }
      throw new Error(`unexpected ${url} ${init?.method}`);
    });
    vi.stubGlobal('fetch', fetchMock);

    await postCodebaseGraphComment(
      'https://gitlab.com/acme/app/-/merge_requests/7',
      { added: ['a.ts'], removed: [] },
    );

    const put = fetchMock.mock.calls.find(([, init]) => init?.method === 'PUT');
    expect(put?.[0]).toContain('/notes/9');
    expect(fetchMock.mock.calls.some(([, init]) => init?.method === 'POST')).toBe(false);
  });
});
