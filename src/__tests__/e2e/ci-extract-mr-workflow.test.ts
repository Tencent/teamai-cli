/**
 * E2E: `teamai ci extract-mr` runs the default workflow teamai-ci-extract-mr on a CI machine with no `teamai init`: an
 * empty HOME, the merged checkout as the working directory, `claude` a stand-in on PATH and the MR's provider a local
 * API. The team repo, when given, is a clone of a local bare repository outside the checkout.
 */
import { execFileSync, spawn } from 'node:child_process';
import fs from 'node:fs';
import http from 'node:http';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, describe, expect, it } from 'vitest';

const CLI = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../dist/index.js');

const GIT_ENV = { GIT_AUTHOR_NAME: 't', GIT_AUTHOR_EMAIL: 't@t', GIT_COMMITTER_NAME: 't', GIT_COMMITTER_EMAIL: 't@t', GIT_TERMINAL_PROMPT: '0' };

const LEARNING = '---\ntitle: "Retry uploads on 5xx"\nauthor: dev\ndate: 2026-11-04\ntags: [retry, s3]\nconfidence: 0.85\n---\n\n## Background\nUploads failed under load.\n';

/** The comment `ci extract-mr` posts for {@link LEARNING}, which it reads with no trailing newline, under `marker`. */
const comment = (marker: string): string => [
  marker, '', '## TeamAI Knowledge Extraction', '', '### Learning', '', '**Retry uploads on 5xx**', '',
  '<details>', '<summary>Show full content</summary>', '', '```markdown', LEARNING.trimEnd(), '```', '', '</details>', '',
  '---', '> These suggestions are applied to the team knowledge repo once the MR is merged.', '> _Auto-generated by `teamai ci extract-mr`_',
].join('\n');

type Ran = { code: number | null; stdout: string; stderr: string };

interface Api {
  origin: string;
  /** Every request but a read of the notes, with its JSON body. */
  requests: Array<{ method: string; path: string; body?: unknown }>;
  close: () => Promise<void>;
}

/** A GitLab and GitHub API: MR 7 merged with one commit, MR 8 missing, and the review `threads` of MR 7. */
async function fakeApi(threads: unknown[] = []): Promise<Api> {
  const requests: Api['requests'] = [];
  const server = http.createServer((req, res) => {
    let body = '';
    req.setEncoding('utf8');
    req.on('data', (chunk: string) => { body += chunk; });
    req.on('end', () => {
      const route = new URL(req.url ?? '/', 'http://fixture').pathname;
      const method = req.method ?? 'GET';

      if (method !== 'GET' || !route.endsWith('/notes')) requests.push({ method, path: route, ...(body ? { body: JSON.parse(body) } : {}) });
      res.setHeader('Content-Type', 'application/json');

      if (route.endsWith('/merge_requests/8')) res.writeHead(404).end('{"message":"404 Not found"}');
      else if (method === 'POST') res.end(JSON.stringify({ id: 55, body: '', html_url: 'https://ghe.example/acme/app/pull/7#issuecomment-55' }));
      else if (route.endsWith('/notes') || route.endsWith('/comments')) res.end('[]');
      else if (route.endsWith('/discussions')) res.end(JSON.stringify(threads));
      else if (route.endsWith('/commits')) res.end(JSON.stringify([{ id: 'abc1234567890', title: 'retry uploads', message: 'retry uploads' }]));
      else if (route.endsWith('/changes')) res.end(JSON.stringify({ changes: [{ new_path: 'up.ts', diff: '+retry(3)\n' }] }));
      else if (route.endsWith('/merge_requests/7')) res.end(JSON.stringify({ title: 'Retry flaky upload', description: 'Uploads fail under load.', author: { username: 'dev' }, merged_at: '2026-11-04T10:00:00Z' }));
      else if (route.endsWith('/user')) res.end(JSON.stringify({ username: 'ci-bot' }));
      else res.writeHead(404).end('{}');
    });
  });
  await new Promise<void>((resolve) => { server.listen(0, '127.0.0.1', resolve); });
  const address = server.address();

  if (!address || typeof address === 'string') throw new Error('Expected a TCP address');

  return {
    origin: `http://127.0.0.1:${address.port}`,
    requests,
    close: () => new Promise<void>((resolve) => { server.closeAllConnections(); server.close(() => resolve()); }),
  };
}

/** `gh` answering for acme/app PR 7, as the GitHub fetch reads it. */
const FAKE_GH = `#!/usr/bin/env bash
if [ "$1" = api ]; then echo '[]'; exit 0; fi
case "$1 $2" in
  "pr view") echo '{"title":"Retry flaky upload","body":"Uploads fail under load.","author":{"login":"dev"},"mergedAt":"2026-11-04T10:00:00Z","commits":[{"oid":"abc12345","messageHeadline":"retry uploads"}]}' ;;
  "pr diff") printf 'diff --git a/up.ts b/up.ts\\n+retry(3)\\n' ;;
  *) echo "fake gh: $*" >&2; exit 1 ;;
esac
`;

interface Sandbox {
  root: string;
  home: string;
  app: string;
  team: string;
  remote: string;
  api: Api;
  /** Each prompt the AI tool was given. */
  prompts: () => string[];
  run: (args: string[], env?: Record<string, string>) => Promise<Ran>;
}

const sandboxes: Sandbox[] = [];

afterEach(async () => {
  for (const sb of sandboxes.splice(0)) {
    await sb.api.close();
    fs.rmSync(sb.root, { recursive: true, force: true });
  }
});

function git(args: string[], cwd: string): string {
  return execFileSync('git', args, { cwd, stdio: 'pipe', env: { ...process.env, ...GIT_ENV } }).toString().trim();
}

/** A CI machine: no teamai init, the merged checkout, and a team repo cloned outside it. */
async function ciMachine(threads: unknown[] = []): Promise<Sandbox> {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'teamai-ci-extract-mr-')));
  const home = path.join(root, 'home');
  const bin = path.join(root, 'bin');
  fs.mkdirSync(home);
  fs.mkdirSync(bin);
  fs.writeFileSync(path.join(root, 'gitconfig'), '[user]\n\tname = t\n\temail = t@t\n[init]\n\tdefaultBranch = main\n');
  fs.writeFileSync(path.join(bin, 'gh'), FAKE_GH, { mode: 0o755 });
  const log = path.join(root, 'claude.log');
  fs.writeFileSync(path.join(bin, 'claude'), `#!${process.execPath}
const fs = require('fs');
let stdin = ''; process.stdin.on('data', (d) => stdin += d); process.stdin.on('end', () => {
  fs.appendFileSync(${JSON.stringify(log)}, JSON.stringify(stdin) + '\\n');
  process.stdout.write(JSON.stringify({ type: 'result', is_error: false, result: ${JSON.stringify(LEARNING)}, usage: { input_tokens: 10, output_tokens: 5 } }));
});\n`, { mode: 0o755 });

  const app = path.join(root, 'app');
  fs.mkdirSync(app);
  git(['init', '-q', '-b', 'main'], app);
  fs.writeFileSync(path.join(app, 'README.md'), 'app\n');
  git(['add', '-A'], app);
  git(['commit', '-qm', 'init'], app);
  fs.writeFileSync(path.join(app, 'README.md'), 'app, with retries\n');
  git(['commit', '-qam', 'merge !7'], app);

  const remote = path.join(root, 'team.git');
  const team = path.join(root, 'team');
  git(['init', '-q', '--bare', '-b', 'main', remote], root);
  git(['clone', '-q', remote, team], root);
  fs.writeFileSync(path.join(team, 'teamai.yaml'), 'team: acme\nrepo: x\nprovider: gitlab\nlanguage: en\n');
  git(['add', '-A'], team);
  git(['commit', '-qm', 'team'], team);
  git(['push', '-q', 'origin', 'HEAD:main'], team);

  const api = await fakeApi(threads);
  const { port } = new URL(api.origin);
  const env = {
    HOME: home, USERPROFILE: home, PATH: `${bin}${path.delimiter}${path.dirname(process.execPath)}${path.delimiter}/usr/bin${path.delimiter}/bin`,
    GIT_CONFIG_GLOBAL: path.join(root, 'gitconfig'), GIT_CONFIG_NOSYSTEM: '1', LC_ALL: 'C.UTF-8', NO_COLOR: '1', FORCE_COLOR: '0', TERM: 'dumb',
    GITLAB_URL: api.origin, TEAMAI_GITLAB_HOST: `127.0.0.1:${port}`, GITLAB_API_PREFIX: 'api/v4', GITLAB_TOKEN: 'fixture-token',
  };

  const run = (args: string[], extra: Record<string, string> = {}): Promise<Ran> => new Promise((resolve) => {
    // Only what a CI job sets: nothing of the session these tests run in.
    const child = spawn(process.execPath, [CLI, 'ci', 'extract-mr', ...args], { cwd: app, env: { ...env, ...extra }, stdio: ['ignore', 'pipe', 'pipe'] });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (d: Buffer) => { stdout += d.toString(); });
    child.stderr.on('data', (d: Buffer) => { stderr += d.toString(); });
    child.on('close', (code) => resolve({ code, stdout, stderr }));
  });

  const prompts = (): string[] => (fs.existsSync(log) ? fs.readFileSync(log, 'utf8').split('\n').filter(Boolean).map((line) => String(JSON.parse(line))) : []);
  const sb = { root, home, app, team, remote, api, prompts, run };
  sandboxes.push(sb);

  return sb;
}

describe('teamai ci extract-mr (real CLI, no teamai init)', () => {
  it('comments through the GitHub API GITHUB_API_URL names, as GitHub Enterprise sets it', async () => {
    const sb = await ciMachine();

    const ran = await sb.run(['--url', 'https://github.com/acme/app/pull/7'], { GITHUB_API_URL: `${sb.api.origin}/api/v3`, GITHUB_TOKEN: 'fixture-token' });

    expect(ran.code, ran.stdout + ran.stderr).toBe(0);
    expect(ran.stdout).toContain('✔ MR comment posted');
    expect(sb.api.requests.filter((request) => request.method !== 'GET')).toEqual([
      { method: 'POST', path: '/api/v3/repos/acme/app/issues/7/comments', body: { body: comment('<!-- teamai:ci-extract -->') } },
    ]);
  });
});
