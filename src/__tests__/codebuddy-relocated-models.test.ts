import path from 'node:path';
import os from 'node:os';
import fse from 'fs-extra';
import { beforeEach, afterEach, expect, it, vi } from 'vitest';
import { ModelProfileSchema, resolveProfile } from '../models/profile.js';
import { switchModelProfile, restoreModelProfiles } from '../models/switch.js';
import { saveToolHomes } from '../tool-home.js';
let home: string;
beforeEach(async () => { home = await fse.mkdtemp(path.join(os.tmpdir(), 'teamai-cb-models-')); vi.stubEnv('HOME', home); vi.stubEnv('USERPROFILE', home); vi.stubEnv('CODEBUDDY_CONFIG_DIR', ''); });
afterEach(async () => { vi.unstubAllEnvs(); await fse.remove(home); });
const profile = () => resolveProfile({ source: 'local', profile: ModelProfileSchema.parse({ id: 'fixture', name: 'Fixture', base_url: 'https://example.test', api_key: '${API_KEY}', model_groups: [{ protocols: ['openai-chat-completions'], models: ['team-model'] }] }) }, { 'local:fixture': { API_KEY: { value: 'test-key' } } });
it.each(['env', 'recorded'] as const)('switches and restores CodeBuddy models through the %s home, preserving the default file', async mode => {
  const moved = path.join(home, 'moved-codebuddy');
  const file = path.join(moved, 'models.json');
  const personal = { models: [{ id: 'personal', name: 'Mine' }] };
  await fse.outputJson(file, personal);
  const old = path.join(home, '.codebuddy/models.json');
  await fse.outputFile(old, '{"models":[]}\n');
  if (mode === 'recorded') await saveToolHomes({ codebuddy: moved });
  else vi.stubEnv('CODEBUDDY_CONFIG_DIR', moved);
  expect((await switchModelProfile(profile(), ['codebuddy']))[0].status).toBe('switched');
  expect((await fse.readJson(file)).models.map((m: { id: string }) => m.id)).toEqual(['personal', 'team-model']);
  expect(await fse.readFile(old, 'utf8')).toBe('{"models":[]}\n');
  expect((await restoreModelProfiles(['codebuddy']))[0].status).toBe('restored');
  expect(await fse.readJson(file)).toEqual(personal);
});
it('refuses to move an active profile into another home and restores its recorded original file', async () => {
  const first = path.join(home, 'first');
  const second = path.join(home, 'second');
  await fse.outputJson(path.join(first, 'models.json'), { models: [] });
  await saveToolHomes({ codebuddy: first });
  expect((await switchModelProfile(profile(), ['codebuddy']))[0].status).toBe('switched');
  await fse.ensureDir(second);
  await saveToolHomes({ codebuddy: second });
  const result = (await switchModelProfile(profile(), ['codebuddy']))[0];
  expect(result.status).toBe('skipped');
  expect(await fse.pathExists(path.join(second, 'models.json'))).toBe(false);
  expect((await restoreModelProfiles(['codebuddy']))[0].status).toBe('skipped');
  await saveToolHomes({ codebuddy: first });
  expect((await restoreModelProfiles(['codebuddy']))[0].status).toBe('restored');
  expect(await fse.readJson(path.join(first, 'models.json'))).toEqual({ models: [] });
});
